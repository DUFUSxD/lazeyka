// Переводы интерфейса. Ключ — русский текст: он же показывается, если перевода нет. {0}, {1} — подстановки.
// Язык ставит load() из настроек (lang): 'auto' — как у браузера, русский только при русском интерфейсе браузера.
let en = false;
export function setLang(v) {
  en = !(v === 'ru' || v === 'en' ? v : chrome.i18n.getUILanguage()).toLowerCase().startsWith('ru');
}
export const lang = () => (en ? 'en' : 'ru');

export function t(key, ...args) {
  const s = (en && EN[key]) || key;
  return args.length ? s.replace(/\{(\d)\}/g, (_, i) => args[i]) : s;
}

// «1 сервер, 2 сервера, 5 серверов» / «1 server, 2 servers»; forms — ключ вида 'сервер|сервера|серверов'
export function plural(n, forms) {
  const f = t(forms).split('|');
  if (f.length === 2) return `${n} ${f[n === 1 ? 0 : 1]}`;
  const i = n % 10 === 1 && n % 100 !== 11 ? 0 : n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 12 || n % 100 > 14) ? 1 : 2;
  return `${n} ${f[i]}`;
}

// Статичный текст popup.html: текстовые узлы и подсказки (title, placeholder, aria-label).
export function translateDom(root) {
  if (!en) return;
  const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let n = w.nextNode(); n; n = w.nextNode()) {
    const k = n.nodeValue.trim();
    if (EN[k]) n.nodeValue = n.nodeValue.replace(k, () => EN[k]);
  }
  for (const el of root.querySelectorAll('[title], [placeholder], [aria-label]')) {
    for (const a of ['title', 'placeholder', 'aria-label']) if (EN[el.getAttribute(a)]) el.setAttribute(a, EN[el.getAttribute(a)]);
  }
}

